def _human_bool(value: bool) -> str:
    return "включено" if value else "выключено"


def bound_status_text(
    *,
    username: str | None,
    bound_at: datetime,
    notifications_enabled: bool,
    notify_medications: bool,
    notify_visits: bool,
    notify_daily_summary: bool,
) -> str:
    username_part = f"@{username}" if username else "(без @username)"
    date_part = bound_at.strftime("%d.%m.%Y %H:%M")
    return (
        f"✅ Привязка активна: <b>{username_part}</b>\n"
        f"Подключено: {date_part}\n\n"
        "<b>Настройки уведомлений:</b>\n"
        f"• Общий выключатель — {_human_bool(notifications_enabled)}\n"
        f"• Препараты — {_human_bool(notify_medications)} <i>(активируется на этапе 10)</i>\n"
        f"• Визиты — {_human_bool(notify_visits)} <i>(активируется на этапе 9)</i>\n"
        f"• Сводка дня — {_human_bool(notify_daily_summary)} <i>(активируется на этапе 10)</i>\n\n"
        "Изменить настройки можно в приложении."
    )


